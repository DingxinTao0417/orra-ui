// Generates src/index.ts: an explicit barrel of every public export.
// Names exported by more than one module are kept from the first module only
// (base → foundations → blocks → utils/hooks); the others stay reachable via
// their deep import path, e.g. "@orra-ui/react/blocks/charts/chart-card".
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "src");
const ORDER = ["lib", "components"];

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (/\.tsx?$/.test(e.name) && !e.name.endsWith(".d.ts")) out.push(p);
  }
  return out;
}

const files = walk(src)
  .filter((f) => path.relative(src, f) !== "index.ts")
  .sort((a, b) => {
    const ra = path.relative(src, a), rb = path.relative(src, b);
    const oa = ORDER.indexOf(ra.split(path.sep)[0]), ob = ORDER.indexOf(rb.split(path.sep)[0]);
    return oa - ob || ra.localeCompare(rb);
  });

const program = ts.createProgram(files, { jsx: ts.JsxEmit.ReactJSX, allowJs: false, skipLibCheck: true, noEmit: true, moduleResolution: ts.ModuleResolutionKind.Bundler, module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 });
const checker = program.getTypeChecker();
const seen = new Map();
const lines = ["// AUTO-GENERATED by scripts/gen-index.mjs — do not edit.", ""];
const dupes = [];

for (const file of files) {
  const sf = program.getSourceFile(file);
  const sym = sf && checker.getSymbolAtLocation(sf);
  if (!sym) continue;
  const values = [], types = [];
  for (const exp of checker.getExportsOfModule(sym)) {
    const name = exp.getName();
    if (name === "default") continue;
    const target = exp.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exp) : exp;
    const isValue = (target.flags & ts.SymbolFlags.Value) !== 0;
    if (seen.has(name)) { dupes.push(`${name}: ${seen.get(name)} / ${path.relative(src, file)}`); continue; }
    seen.set(name, path.relative(src, file));
    (isValue ? values : types).push(name);
  }
  if (!values.length && !types.length) continue;
  const spec = "./" + path.relative(src, file).replace(/\\/g, "/").replace(/\.tsx?$/, "");
  const parts = [...values, ...types.map((t) => `type ${t}`)];
  lines.push(`export { ${parts.join(", ")} } from "${spec}";`);
}
fs.writeFileSync(path.join(src, "index.ts"), lines.join("\n") + "\n");
console.log(`[gen-index] ${seen.size} exports from ${files.length} modules; ${dupes.length} duplicate names skipped`);
if (process.env.VERBOSE) console.log(dupes.join("\n"));
